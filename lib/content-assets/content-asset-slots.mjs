/**
 * Normalizuje relativnu putanju i odbija sve sto moze da izadje iz korena.
 *
 * Odbija: apsolutne putanje, `..` segmente, backslash putanje i NUL znak.
 * Vraca putanju sa jednom kosom crtom kao separatorom, bez vodece `./`.
 *
 * @param {unknown} raw
 * @returns {{ ok: true, value: string } | { ok: false, reason: string }}
 */
export function normalizeRelativePath(raw) {
  if (typeof raw !== "string" || raw === "") {
    return { ok: false, reason: "putanja mora biti neprazan string" };
  }
  if (raw.includes("\0")) return { ok: false, reason: "putanja sadrzi NUL znak" };
  if (raw.includes("\\")) return { ok: false, reason: "putanja sadrzi backslash" };
  if (raw.startsWith("/")) return { ok: false, reason: "putanja je apsolutna" };
  if (/^[A-Za-z]:/.test(raw)) return { ok: false, reason: "putanja je apsolutna (Windows disk)" };

  const segments = [];
  for (const segment of raw.split("/")) {
    if (segment === "" || segment === ".") continue;
    if (segment === "..") return { ok: false, reason: "putanja sadrzi `..`" };
    segments.push(segment);
  }
  if (segments.length === 0) return { ok: false, reason: "putanja je prazna posle normalizacije" };
  // Zavrsna kosa crta se cuva: `targetPath` je folder, ne fajl.
  const trailing = raw.endsWith("/") ? "/" : "";
  return { ok: true, value: segments.join("/") + trailing };
}

/**
 * Pun spisak ciljnih FAJLOVA jednog slota.
 *
 * `targetPath` je folder i vise slotova sme da ga deli; ono sto mora biti
 * jedinstveno je konacan fajl. Sabloni sa `{` su jos neodluceni i preskacu se.
 *
 * @param {Record<string, unknown>} slot
 * @returns {string[]}
 */
export function targetFilesFor(slot) {
  const base = typeof slot.targetPath === "string" ? slot.targetPath : "";
  const out = [];
  for (const key of ["expectedDesktopFilename", "expectedMobileFilename"]) {
    const name = slot[key];
    if (typeof name !== "string" || name === "" || name.includes("{")) continue;
    out.push(`${base.endsWith("/") ? base : base + "/"}${name}`);
  }
  return out;
}

/**
 * Validira kanonske podatke. Vraca spisak problema; prazan spisak znaci ispravno.
 *
 * Namerno vraca SVE probleme, ne prvi — jedan prolaz mora pokazati ceo posao.
 *
 * @param {ReadonlyArray<Record<string, unknown>>} slots
 * @returns {string[]}
 */
export function validateSlots(slots = CONTENT_ASSET_SLOTS) {
  const problems = [];
  const vidjeniId = new Set();
  const vidjeniCilj = new Map();

  slots.forEach((slot, index) => {
    const id = typeof slot.slotId === "string" ? slot.slotId : `#${index}`;

    if (typeof slot.slotId !== "string" || slot.slotId === "") {
      problems.push(`${id}: slotId mora biti neprazan string`);
    } else if (vidjeniId.has(slot.slotId)) {
      problems.push(`${id}: duplikat slotId`);
    } else {
      vidjeniId.add(slot.slotId);
    }

    if (!VALID_STATUS.has(slot.status)) problems.push(`${id}: nevalidan status "${slot.status}"`);
    if (!VALID_PRIORITY.has(slot.priority)) problems.push(`${id}: nevalidan prioritet "${slot.priority}"`);

    const cilj = normalizeRelativePath(slot.targetPath);
    if (!cilj.ok) {
      problems.push(`${id}: targetPath odbijen — ${cilj.reason}`);
    } else {
      if (!cilj.value.startsWith(TARGET_ROOT)) {
        problems.push(`${id}: targetPath je van "${TARGET_ROOT}" (${cilj.value})`);
      }
      if (cilj.value !== slot.targetPath) {
        problems.push(`${id}: targetPath nije normalizovan (ocekivano "${cilj.value}")`);
      }
    }

    for (const fajl of targetFilesFor(slot)) {
      const p = normalizeRelativePath(fajl);
      if (!p.ok) {
        problems.push(`${id}: ciljni fajl odbijen — ${p.reason}`);
        continue;
      }
      const prethodni = vidjeniCilj.get(p.value);
      if (prethodni !== undefined) {
        problems.push(`${id}: ciljna putanja se sudara sa ${prethodni} (${p.value})`);
      } else {
        vidjeniCilj.set(p.value, id);
      }
    }

    for (const key of ["expectedDesktopFilename", "expectedMobileFilename"]) {
      const name = slot[key];
      if (typeof name !== "string" || name === "" || name.includes("{")) continue;
      if (name.includes("/") || name.includes("\\")) {
        problems.push(`${id}: ${key} sadrzi separator putanje`);
      }
      if (name !== name.toLowerCase()) problems.push(`${id}: ${key} nije lowercase`);
    }
  });

  return problems;
}

/** Stabilan redosled: po `slotId`, nezavisno od redosleda pisanja. */
export function sortedSlots(slots = CONTENT_ASSET_SLOTS) {
  return [...slots].sort((a, b) => String(a.slotId).localeCompare(String(b.slotId), "en"));
}
